package com.ascend.app.di

/** Звуки интерфейса. Все они синтезируются процедурно — в приложении нет аудиофайлов. */
enum class Sound {
    /** Лёгкий тик при нажатии на галочку. */
    TAP,
    /** Квест выполнен: короткий мажорный перезвон. */
    COMPLETE,
    /** Комбо: тот же перезвон, но выше и ярче. */
    COMBO,
    /** Монеты: звон при покупке и начислении золота. */
    COIN,
    /** Достижение или испытание: трёхнотная фанфара. */
    ACHIEVEMENT,
    /** Новый уровень: восходящее арпеджио. */
    LEVEL_UP,
    /** Удар по боссу: низкий глухой удар. */
    BOSS_HIT,
    /** Босс повержен: торжественный аккорд. */
    BOSS_DEFEATED,
    /** Таймер фокуса завершён: мягкий колокольчик. */
    TIMER_DONE,
}

/** Проигрыватель звуков. Реализация живёт в Android-слое; по умолчанию — тишина. */
interface SoundPlayer {
    fun play(sound: Sound)

    object None : SoundPlayer {
        override fun play(sound: Sound) = Unit
    }
}
