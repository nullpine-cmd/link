    fun encouragement(reward: Reward, hasTarget: Boolean, seed: Int): String {
        val pool = when {
            reward.comeback -> comeback
            reward.comboStep >= 2 -> combo
            reward.overachieved -> overachieve
            hasTarget && reward.hitTarget -> targetHit
            hasTarget -> partialProgress
            else -> simple
        }
        return pool[Math.floorMod(seed, pool.size)]
    }

    fun dayProgressMessage(done: Int, total: Int): String = when {
        total == 0 -> "Добавь квест — даже самый маленький шаг засчитается"
        done == 0 -> "Начни с малого: любой прогресс засчитывается"
        done == total -> "Все квесты дня выполнены. Легендарно!"
